def gear(size=256,kind=0):
    scale=2;im=Image.new('RGBA',(size*scale,size*scale),(0,0,0,0));d=ImageDraw.Draw(im)
    c=size*scale/2;r=size*scale*.36;gold=(204,174,112,240)
    pts=[]
    for i in range(96):
        a=i*math.pi/48;rr=r*(1.12 if i%4 in [1,2] else 1)
        pts.append((c+rr*math.cos(a),c+rr*math.sin(a)))
    d.line(pts+[pts[0]],fill=gold,width=max(2,size//64),joint='curve')
    for f in [.83,.65]:d.ellipse((c-r*f,c-r*f,c+r*f,c+r*f),outline=gold,width=max(2,size//100))
    d.arc((c-r*.35,c-r*.35,c+r*.35,c+r*.35),45,315,fill=(216,225,227,255),width=max(3,size//45))
    return im.resize((size,size),Image.Resampling.LANCZOS)

